@cache
def core_font_widths(name: str) -> dict[str, int] | None:
    """pypdf's widths, by character, of the core font of that name, or None."""
    if name == "ZapfDingbats":
        return ZAPF_DINGBATS_WIDTHS
    source = CORE_FONT_SOURCES.get(name)
    if source is None:
        return None
    base, euro = source
    widths = {str(key): int(value) for key, value in FONT_DATA[base]["widths"].items()}
    widths["\u20ac"] = euro
    return widths
